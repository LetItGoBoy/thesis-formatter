/**
 * 栈混洗可行性判定（贪心模拟）：
 * 依次满足 target 中的每个需求；栈顶不匹配就继续从输入推入，
 * 输入耗尽仍不匹配则不可行。
 */
export function canShuffle(input: number[], target: number[]): boolean {
  const stack: number[] = [];
  let i = 0;
  for (const need of target) {
    while (stack[stack.length - 1] !== need && i < input.length) {
      stack.push(input[i++]);
    }
    if (stack[stack.length - 1] === need) stack.pop();
    else return false;
  }
  return true;
}
